def validate_recipe_catalog() -> list[str]:
    """Validate every recipe in EXPANDED_RECIPE_CATALOG for structure, quantities, units, and steps."""
    errors: list[str] = []
    seen_ids: set[str] = set()
    seen_titles: set[str] = set()
    for rec in EXPANDED_RECIPE_CATALOG:
        rid = rec.get("recipe_id")
        title = rec.get("title")
        if not rid or rid in seen_ids:
            errors.append(f"Duplicate or missing recipe_id: {rid}")
        seen_ids.add(str(rid))
        if not title or title in seen_titles:
            errors.append(f"Duplicate or missing title: {title}")
        seen_titles.add(str(title))
        if not rec.get("cuisine") or not rec.get("meal_types"):
            errors.append(f"Missing cuisine/meal_types on {title}")
        ings = rec.get("ingredients") or []
        if not ings or not any(not i.get("is_optional") for i in ings):
            errors.append(f"Missing essential ingredients on {title}")
        for ing in ings:
            if float(ing.get("qty") or 0) <= 0 or ing.get("unit") not in ("g", "ml", "pcs"):
                errors.append(f"Invalid ingredient qty/unit on {title}: {ing}")
        if len(rec.get("steps") or []) < 1:
            errors.append(f"Missing steps on {title}")
    return errors
