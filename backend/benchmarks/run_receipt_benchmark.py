def _levenshtein(a: str, b: str) -> int:
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        curr = [i]
        for j, cb in enumerate(b, 1):
            cost = 0 if ca == cb else 1
            curr.append(min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost))
        prev = curr
    return prev[-1]


def _cer(pred: str, ref: str) -> float:
    if not ref:
        return 0.0
    return round(_levenshtein(pred, ref) / max(len(ref), 1), 4)


def _wer(pred: str, ref: str) -> float:
    p_words = pred.split()
    r_words = ref.split()
    if not r_words:
        return 0.0
    if not p_words:
        return 1.0
    # Word-level Levenshtein
    prev = list(range(len(r_words) + 1))
    for i, pw in enumerate(p_words, 1):
        curr = [i]
        for j, rw in enumerate(r_words, 1):
            cost = 0 if pw == rw else 1
            curr.append(min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost))
        prev = curr
    return round(prev[-1] / max(len(r_words), 1), 4)


def _render_receipt_card(
    lines: list[str],
    *,
    width: int = 580,
    bg: tuple[int, int, int] = (246, 245, 240),
    ink: tuple[int, int, int] = (25, 25, 28),
    font_size: int = 22,
) -> np.ndarray:
    line_h = font_size + 14
    height = max(420, 60 + len(lines) * line_h)
    img = Image.new("RGB", (width, height), bg)
    draw = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", font_size)
    except Exception:
        font = ImageFont.load_default(size=font_size)
    y = 30
    for ln in lines:
        draw.text((28, y), ln, fill=ink, font=font)
        y += line_h
    return cv2.cvtColor(np.array(img), cv2.COLOR_RGB2BGR)


def _place_on_background(
    card_bgr: np.ndarray,
    *,
    bg_color: tuple[int, int, int],
    angle_deg: float = 0.0,
    perspective: bool = False,
    shadow: bool = False,
    glare: bool = False,
    blur_k: int = 0,
    finger: bool = False,
) -> bytes:
    ch, cw = card_bgr.shape[:2]
    pad_x, pad_y = 180, 140
    canvas = np.full((ch + 2 * pad_y, cw + 2 * pad_x, 3), bg_color, dtype=np.uint8)
    # Subtle wood/table grain noise
    rng = np.random.default_rng(42)
    noise = rng.integers(-8, 9, size=canvas.shape, dtype=np.int16)
    canvas = np.clip(canvas.astype(np.int16) + noise, 0, 255).astype(np.uint8)

    if perspective:
        src = np.float32([[0, 0], [cw, 0], [cw, ch], [0, ch]])
        dst = np.float32(
            [
                [pad_x + 35, pad_y + 15],
                [pad_x + cw - 20, pad_y + 40],
                [pad_x + cw - 5, pad_y + ch - 10],
                [pad_x + 10, pad_y + ch - 30],
            ]
        )
        m = cv2.getPerspectiveTransform(src, dst)
        mask = np.full((ch, cw), 255, dtype=np.uint8)
        warped_card = cv2.warpPerspective(card_bgr, m, (canvas.shape[1], canvas.shape[0]))
        warped_mask = cv2.warpPerspective(mask, m, (canvas.shape[1], canvas.shape[0])) > 128
        canvas[warped_mask] = warped_card[warped_mask]
    else:
        canvas[pad_y : pad_y + ch, pad_x : pad_x + cw] = card_bgr

    if angle_deg != 0.0:
        h, w = canvas.shape[:2]
        m_rot = cv2.getRotationMatrix2D((w / 2.0, h / 2.0), angle_deg, 1.0)
        canvas = cv2.warpAffine(canvas, m_rot, (w, h), borderValue=bg_color)

    if finger:
        # Partial finger occlusion on bottom-left edge (outside text)
        cv2.ellipse(
            canvas, (pad_x + 15, pad_y + ch - 40), (45, 75), -20, 0, 360, (135, 165, 210), -1
        )

    if shadow:
        grad = np.linspace(0.55, 1.0, canvas.shape[1], dtype=np.float32)[None, :, None]
        canvas = np.clip(canvas.astype(np.float32) * grad, 0, 255).astype(np.uint8)

    if glare:
        h, w = canvas.shape[:2]
        yy, xx = np.ogrid[:h, :w]
        dist = np.sqrt((xx - w * 0.55) ** 2 + (yy - h * 0.35) ** 2)
        spot = np.clip(1.0 - dist / (min(h, w) * 0.28), 0.0, 1.0)[:, :, None]
        canvas = np.clip(canvas.astype(np.float32) + spot * 110.0, 0, 255).astype(np.uint8)

    if blur_k > 0:
        canvas = cv2.GaussianBlur(canvas, (blur_k, blur_k), 0)

    ok, buf = cv2.imencode(".jpg", canvas, [cv2.IMWRITE_JPEG_QUALITY, 90])
    assert ok
    return buf.tobytes()


def _make_pdf_bytes(lines: list[str], *, pages: int = 1, scanned: bool = False) -> bytes:
    doc = fitz.open()
    if scanned:
        card = _render_receipt_card(lines)
        ok, png = cv2.imencode(".png", card)
        assert ok
        page = doc.new_page(width=595, height=842)
        page.insert_image(fitz.Rect(40, 40, 555, 800), stream=png.tobytes())
    else:
        chunk = max(1, (len(lines) + pages - 1) // pages)
        for p in range(pages):
            page = doc.new_page()
            sub = lines[p * chunk : (p + 1) * chunk]
            page.insert_text((50, 72), "\n".join(sub), fontsize=12)
    data = doc.tobytes()
    doc.close()
    return data


